/** `focus_minutes({ minutes: 25 })` → "25 min". */
export function m(key, values = {}) {
  return String(M[key] ?? key).replace(/\{(\w+)\}/gu, (whole, name) =>
    values[name] === undefined ? whole : String(values[name]),
  );
}
